def get_min_notional(symbol: str) -> float:
    """获取交易对的最小名义价值"""
    return float(MIN_NOTIONAL.get(symbol, DEFAULT_MIN_NOTIONAL))


def get_qty_precision(symbol: str) -> int:
    """获取交易对的数量精度 (小数位数)"""
    return QUANTITY_PRECISION.get(symbol, 2)


def get_step_size(symbol: str) -> str:
    """获取交易对的数量步长"""
    return STEP_SIZE.get(symbol, "0.01")


def get_tick_size(symbol: str) -> str:
    """获取交易对的价格步长"""
    return TICK_SIZE.get(symbol, "0.01")


def round_quantity(symbol: str, quantity: float) -> float:
    """按交易对精度取整下单数量 (向下取整)"""
    import math
    precision = get_qty_precision(symbol)
    factor = 10 ** precision
    return math.floor(quantity * factor) / factor


def round_quantity_up(symbol: str, quantity: float) -> float:
    """按交易对精度向上取整 (用于计算最小满足名义要求的数量)"""
    import math
    precision = get_qty_precision(symbol)
    factor = 10 ** precision
    return math.ceil(quantity * factor) / factor


def validate_order(symbol: str, quantity: float, price: float, leverage: int = 1) -> dict:
    """
    验证订单参数是否符合交易所规则
    
    Returns:
        dict with "valid" (bool), "error" (str), "suggestion" (dict)
    """
    min_notional = get_min_notional(symbol)
    notional = quantity * price
    
    if notional < min_notional:
        min_qty = round_quantity_up(symbol, min_notional / price)
        suggested_margin = (min_qty * price) / leverage if leverage > 0 else min_qty * price
        return {
            "valid": False,
            "error": (
                f"名义价值不足: {quantity} × ${price:,.2f} = ${notional:,.2f}, "
                f"但 {symbol} 最小名义为 ${min_notional}。\n"
                f"建议: quantity={min_qty} (名义=${min_qty * price:,.2f}), "
                f"保证金约 ${suggested_margin:,.2f} ({leverage}x杠杆)"
            ),
            "suggestion": {
                "symbol": symbol,
                "min_quantity": min_qty,
                "min_notional": min_notional,
                "suggested_margin": round(suggested_margin, 2),
                "current_price": price,
            }
        }
    
    return {"valid": True, "error": None, "suggestion": None}

